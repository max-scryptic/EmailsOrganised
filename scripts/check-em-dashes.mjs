#!/usr/bin/env node

/**
 * The em dash ban, enforced.
 *
 * No em dash is allowed anywhere in this repository: not in UI copy, not in a
 * comment, not in a doc, not in a prompt the product sends to a model. Use a
 * comma, a colon, a semicolon, parentheses, or two sentences.
 *
 * Two modes:
 *
 *   node scripts/check-em-dashes.mjs [path...]   scan (no path = every tracked
 *                                                file). Runs in `npm run lint`
 *                                                and in CI.
 *   node scripts/check-em-dashes.mjs --hook      read a Claude Code PreToolUse
 *                                                payload on stdin and block the
 *                                                write before it lands.
 *
 * ESLint carries the same rule for strings and JSX in `eslint.config.mjs`, but
 * it cannot see comments, Markdown, CSS, or SQL, which is why this exists.
 */

import { execFileSync } from "node:child_process";
import { readFileSync, statSync } from "node:fs";
import path from "node:path";

/**
 * The em dash and the characters that get reached for when it is banned: the
 * two- and three-em dashes and the horizontal bar all render as the same
 * punctuation. Escapes and HTML entities are listed because a rule that only
 * looks for the literal character is one `—` away from being decorative.
 */
const banned = [
  { pattern: /—/g, name: "em dash (—)" },
  { pattern: /⸺/g, name: "two-em dash (⸺)" },
  { pattern: /⸻/g, name: "three-em dash (⸻)" },
  { pattern: /―/g, name: "horizontal bar (―)" },
  { pattern: /&mdash;/gi, name: "&mdash; entity" },
  { pattern: /&#8212;|&#x2014;/gi, name: "numeric em dash entity" },
  { pattern: /\\u2014|\\x\{2014\}|\\N\{EM DASH\}/gi, name: "escaped em dash" },
];

/** Punctuation that says the same thing without the character. */
const advice =
  "Use a comma, a colon, a semicolon, parentheses, or two sentences instead.";

/**
 * Vendored third-party agent tooling. Committed so it travels with the repo,
 * but not ours to rewrite, and already excluded from ESLint for the same
 * reason. `package-lock.json` is generated by npm.
 */
const excludedPaths = [".claude/", "node_modules/", "package-lock.json"];

/**
 * The two files that define the rule. Both have to spell out the characters
 * they ban, so neither can be held to it. Nothing else is ever added here: a
 * file that wants an em dash wants the rule not to apply, which is the whole
 * thing this refuses.
 */
const ruleFiles = new Set(["scripts/check-em-dashes.mjs", "eslint.config.mjs"]);

/** Nothing readable as text lives in these. */
const excludedExtensions = new Set([
  ".png",
  ".jpg",
  ".jpeg",
  ".gif",
  ".webp",
  ".ico",
  ".woff",
  ".woff2",
  ".ttf",
  ".otf",
  ".pdf",
  ".zip",
]);

/**
 * Regions written by a tool rather than by us. `next dev` rewrites its block in
 * `AGENTS.md` on every run, em dashes and all, so flagging it would fail the
 * check on a clean checkout the moment anyone starts the dev server.
 */
const generatedBlocks = [
  {
    file: "AGENTS.md",
    start: "<!-- BEGIN:nextjs-agent-rules -->",
    end: "<!-- END:nextjs-agent-rules -->",
  },
];

function isExcluded(file) {
  const normalised = file.split(path.sep).join("/");
  return (
    ruleFiles.has(normalised) ||
    excludedPaths.some((prefix) => normalised.startsWith(prefix)) ||
    excludedExtensions.has(path.extname(normalised).toLowerCase())
  );
}

function generatedRanges(file) {
  return generatedBlocks.filter((block) => block.file === file);
}

/**
 * Every banned occurrence in one file's text, as `{ line, column, name, text }`.
 * Lines inside a generated block are skipped.
 */
export function findEmDashes(contents, file = "") {
  const blocks = generatedRanges(file);
  const findings = [];
  let inGenerated = false;

  contents.split("\n").forEach((text, index) => {
    const opening = blocks.find((block) => text.includes(block.start));
    if (opening) {
      inGenerated = true;
    }

    if (!inGenerated) {
      for (const { pattern, name } of banned) {
        pattern.lastIndex = 0;
        let match;
        while ((match = pattern.exec(text)) !== null) {
          findings.push({ line: index + 1, column: match.index + 1, name, text });
        }
      }
    }

    if (inGenerated && blocks.some((block) => text.includes(block.end))) {
      inGenerated = false;
    }
  });

  return findings;
}

function trackedFiles() {
  return execFileSync("git", ["ls-files", "-z"], { encoding: "utf8" })
    .split("\0")
    .filter(Boolean);
}

function readIfText(file) {
  try {
    if (!statSync(file).isFile()) {
      return null;
    }
    return readFileSync(file, "utf8");
  } catch {
    return null;
  }
}

function scan(paths) {
  const files = (paths.length > 0 ? paths : trackedFiles()).filter(
    (file) => !isExcluded(file)
  );
  let found = 0;

  for (const file of files) {
    const contents = readIfText(file);
    if (contents === null) {
      continue;
    }

    for (const finding of findEmDashes(contents, file)) {
      found += 1;
      console.error(
        `${file}:${finding.line}:${finding.column}  ${finding.name}\n    ${finding.text.trim()}`
      );
    }
  }

  if (found > 0) {
    console.error(
      `\n${found} em dash${found === 1 ? "" : "es"} found. ${advice}`
    );
    process.exit(1);
  }

  console.log(`No em dashes in ${files.length} files.`);
}

/**
 * Blocks an Edit/Write before it happens. Exit code 2 is how a Claude Code hook
 * denies a tool call, with stderr going back to the model as the reason.
 */
async function hook() {
  let payload = "";
  for await (const chunk of process.stdin) {
    payload += chunk;
  }

  let input;
  try {
    input = JSON.parse(payload || "{}");
  } catch {
    // An unreadable payload is not a licence to write an em dash, but it is
    // also not evidence of one. Let the scan in `npm run lint` be the backstop.
    process.exit(0);
  }

  const toolInput = input.tool_input ?? {};
  const file = toolInput.file_path ?? toolInput.notebook_path ?? "";
  const relative = file ? path.relative(process.cwd(), file) : "";

  if (relative && isExcluded(relative)) {
    process.exit(0);
  }

  const written = [
    toolInput.content,
    toolInput.new_string,
    toolInput.new_source,
    ...(Array.isArray(toolInput.edits)
      ? toolInput.edits.map((edit) => edit?.new_string)
      : []),
  ]
    .filter((value) => typeof value === "string")
    .join("\n");

  const findings = findEmDashes(written, relative);
  if (findings.length === 0) {
    process.exit(0);
  }

  const names = [...new Set(findings.map((finding) => finding.name))].join(", ");
  console.error(
    `Blocked: this edit writes ${names}${relative ? ` to ${relative}` : ""}. ` +
      "This repository bans the em dash everywhere, including comments, copy, " +
      `and prompts. ${advice}`
  );
  process.exit(2);
}

const args = process.argv.slice(2);

if (args.includes("--hook")) {
  await hook();
} else {
  scan(args);
}
